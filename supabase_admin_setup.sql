revoke all on function public.kredo_admin_grant_points(uuid, integer, text) from public, anon, authenticated;
revoke all on function public.kredo_admin_recent_point_adjustments() from public, anon, authenticated;

grant execute on function public.kredo_redeem_reward(text) to authenticated;
grant execute on function public.kredo_admin_recent_reward_redemptions() to authenticated;
grant execute on function public.kredo_admin_is_authorized() to authenticated;
grant execute on function public.kredo_admin_dashboard() to authenticated;
